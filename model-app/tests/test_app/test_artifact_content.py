def _seed_imported_version_and_artifact(
    engine, business_id: str, file_path: str,
    artifact_type: str = "model_json",
    version: int = 1, scope: str = "mvm",
) -> tuple[str, str]:
    """Create an imported ModelVersion + RunArtifact with run_id=NULL.

    Mirrors the path the import-from-Volume flow takes: ModelVersion has
    ``import_source_path`` set; ``RunArtifact.run_id`` is NULL (since
    ``v_0_5_0`` made the column nullable for "imports are syncs, not runs").
    """
    from vibe_modeling.backend.db_models import ModelVersion
    with Session(engine) as session:
        mv = ModelVersion(
            business_id=business_id,
            version=version,
            status="completed",
            scope=scope,
            import_source_path="/Volumes/c/_metamodel/vol_root/imports/x/model.json",
        )
        session.add(mv)
        session.commit()
        session.refresh(mv)

        artifact = RunArtifact(
            run_id=None,
            model_version_id=mv.id,
            artifact_type=artifact_type,
            file_path=file_path,
        )
        session.add(artifact)
        session.commit()
        session.refresh(artifact)
        return mv.id, artifact.id


