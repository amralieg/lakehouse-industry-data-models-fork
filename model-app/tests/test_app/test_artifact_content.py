class TestArtifactListByVersionWithNullRunId:
    """Regression test for the HTTP 500 the user reported on 2026-05-18:
    /api/businesses/{bid}/model-versions/{id}/artifacts returned 500 because
    ``RunArtifactOut.run_id`` was typed ``str`` but imported rows have
    ``run_id=None``. Fix: ``RunArtifactOut.run_id: Optional[str] = None``.
    """

    def test_list_imported_artifacts_returns_200_with_null_run_id(
        self, client_with_agent, seed_business, engine
    ):
        bid = seed_business
        mv_id, art1 = _seed_imported_version_and_artifact(
            engine, seed_business, "/Volumes/c/m/imports/model.json",
        )
        # Add a couple more so the response list serialises all of them
        with Session(engine) as session:
            for path, atype in [
                ("/Volumes/c/m/imports/vibes/current_vibes.txt", "text"),
                ("/Volumes/c/m/imports/vibes/next_vibes.txt", "text"),
            ]:
                session.add(RunArtifact(
                    run_id=None, model_version_id=mv_id,
                    artifact_type=atype, file_path=path,
                ))
            session.commit()

        r = client_with_agent.get(
            f"/api/businesses/{bid}/model-versions/{mv_id}/artifacts"
        )
        assert r.status_code == 200, r.text
        rows = r.json()
        assert len(rows) == 3
        for row in rows:
            assert row["run_id"] is None
            assert row["model_version_id"] == mv_id


